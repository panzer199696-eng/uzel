#pragma once

// Обработка звука перед кодеком: ФВЧ → усиление → мягкий лимитер.
//
// Зачем (замер 26.10.2026 на 1,6 ч записей с телефона): 71,5 % энергии сигнала
// лежало ниже 30 Гц — удары, шаги и трение одежды. Этот гул забивал уровень,
// давал клиппинг в 21 % фрагментов и ложные срабатывания VAD, а речь при этом
// шла на −51 dBFS. ФВЧ убирает гул, после него появляется ~30 дБ запаса, и речь
// можно поднять цифровым усилением; редкие пики гасит лимитер.
//
// Модуль без зависимостей от Zephyr — собирается и тестируется на ПК
// (firmware/tests/test_dsp.c).

#include <stddef.h>
#include <stdint.h>

typedef struct
{
    // Биквад ФВЧ, транспонированная прямая форма II
    float b0, b1, b2, a1, a2;
    float z1, z2;
    float gain;            // линейный множитель
    float limit;           // порог мягкого лимитера, доля полной шкалы
    uint32_t limited;      // сколько отсчётов прошло через лимитер (для статистики)
} dsp_state_t;

// fs — частота дискретизации, hpf_hz — срез ФВЧ (Баттерворт 2-го порядка),
// gain_db — цифровое усиление после фильтра, limit — порог лимитера (0..1).
void dsp_init(dsp_state_t *st, float fs, float hpf_hz, float gain_db, float limit);

// Обработка блока на месте.
void dsp_process(dsp_state_t *st, int16_t *pcm, size_t n);
